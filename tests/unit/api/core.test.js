test('cache and freeze:', function (t) {
  const doc = nlp(txt)
  doc.cache()
  t.equal(doc.match('pingüino').text(), 'pingüino', here + 'word match on a cached doc')
  t.equal(doc.match('#Foo').found, false, here + 'tag match on a cached doc')
  doc.uncache()
  t.equal(doc.match('pingüino').text(), 'pingüino', here + 'uncache')
  const d = nlp('el ñandú duerme')
  d.match('ñandú').tag('Ave').freeze()
  d.match('ñandú').unTag('Ave')
  t.equal(d.match('ñandú').has('#Ave'), true, here + 'a frozen tag stays')
  d.unfreeze()
  d.match('ñandú').unTag('Ave')
  t.equal(d.match('ñandú').has('#Ave'), false, here + 'unfreeze')
  t.end()
})

test('contractions:', function (t) {
  const doc = nlp('Vamos al parque del niño.')
  t.equal(doc.text(), 'Vamos al parque del niño.', here + 'text is unchanged')
  t.equal(doc.wordCount(), 5, here + 'wordCount counts the written words')
  t.equal(doc.terms().length, 7, here + 'al and del are two terms each')
  t.equal(doc.match('a el parque').text(), 'al parque', here + 'a el')
  t.equal(doc.match('de el niño').text(), 'del niño', here + 'de el')
  t.equal(doc.match('al parque').found, true, here + 'al')
  t.equal(doc.text('machine'), 'vamos a el parque de el niño.', here + 'machine text')
  const json = doc.json()[0].terms
  t.equal(json[1].text, 'al', here + 'json text')
  t.equal(json[1].implicit, 'a', here + 'json implicit')
  t.equal(json[2].implicit, 'el', here + 'json second half')
  // and its offset is still right
  const m = doc.match('parque').json({ offset: true })[0]
  t.equal('Vamos al parque del niño.'.substr(m.offset.start, m.offset.length), 'parque', here + 'offset after a contraction')
  t.end()
})
