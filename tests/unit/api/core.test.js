import test from 'tape'
import nlp from '../../_lib.js'
const here = '[es-core] '
const txt = 'El niño pequeño corrió hacia la montaña. ¿Dónde está el pingüino? ¡Qué sorpresa!'

test('text output:', function (t) {
  const doc = nlp(txt)
  t.equal(doc.text(), txt, here + 'text is unchanged')
  t.equal(doc.length, 3, here + 'three sentences')
  t.equal(doc.wordCount(), 13, here + 'wordCount')
  t.equal(doc.terms().length, 13, here + 'terms')
  t.equal(doc.eq(1).text(), '¿Dónde está el pingüino?', here + 'eq')
  t.equal(doc.first().text(), 'El niño pequeño corrió hacia la montaña.', here + 'first')
  t.equal(doc.last().text(), '¡Qué sorpresa!', here + 'last')
  t.equal(doc.slice(1).text(), '¿Dónde está el pingüino? ¡Qué sorpresa!', here + 'slice')
  t.equal(doc.text('normal'), 'el niño pequeño corrió hacia la montaña. ¿dónde está el pingüino? ¡qué sorpresa!', here + 'normal text keeps ñ and accents')
  t.deepEqual(doc.out('array'), ['El niño pequeño corrió hacia la montaña.', '¿Dónde está el pingüino?', '¡Qué sorpresa!'], here + 'out array')
  t.equal(doc.terms().eq(1).text(), 'niño', here + 'terms eq')
  t.equal(doc.firstTerms().out('array').join(' '), 'El ¿Dónde ¡Qué', here + 'firstTerms')
  t.equal(doc.lastTerms().out('array').join(' '), 'montaña. pingüino? sorpresa!', here + 'lastTerms')
  t.equal(doc.none().found, false, here + 'none')
  t.equal(doc.match('pingüino').all().text(), txt, here + 'all')
  t.equal(doc.match('pingüino').fullSentences().text(), '¿Dónde está el pingüino?', here + 'fullSentences')
  t.end()
})

test('json output:', function (t) {
  const json = nlp(txt).json()
  t.equal(json.length, 3, here + 'json sentences')
  t.equal(json[0].text, 'El niño pequeño corrió hacia la montaña.', here + 'json text')
  t.equal(json[0].terms.length, 7, here + 'json terms')
  t.equal(json[0].terms[6].text, 'montaña', here + 'json term text')
  t.equal(json[0].terms[6].normal, 'montaña', here + 'json normal')
  t.equal(json[0].terms[6].post, '. ', here + 'json post')
  t.equal(json[1].terms[0].pre, '¿', here + 'json pre')
  t.equal(json[1].terms[0].text, 'Dónde', here + '¿ is not in the word')
  t.equal(json[1].terms[0].normal, 'dónde', here + 'normal keeps the accent')
  t.equal(json[2].terms[0].pre, '¡', here + '¡ is punctuation')
  t.ok(Array.isArray(json[0].terms[1].tags), here + 'json tags are an array')
  const off = nlp(txt).json({ offset: true })
  t.equal(off[1].offset.start, 41, here + 'offset start')
  t.equal(txt.substr(off[1].offset.start, off[1].offset.length), '¿Dónde está el pingüino?', here + 'offset length')
  let m = nlp(txt).match('montaña').json({ offset: true })[0]
  t.equal(txt.substr(m.offset.start, 7), 'montaña', here + 'offset of a match, after ñ')
  m = nlp(txt).match('pingüino').json({ offset: true })[0]
  t.equal(txt.substr(m.offset.start, 8), 'pingüino', here + 'offset of a match, after ¿')
  m = nlp(txt).match('dónde').json({ offset: true })[0]
  t.equal(txt.substr(m.offset.start, m.offset.length), '¿Dónde', here + 'offset of a word with ¿')
  m = nlp(txt).match('sorpresa').json({ offset: true })[0]
  t.equal(txt.substr(m.offset.start, 8), 'sorpresa', here + 'offset of a match, in the last sentence')
  t.end()
})

test('match in spanish:', function (t) {
  const doc = nlp(txt)
  t.equal(doc.match('montaña').text(), 'montaña', here + 'ñ matches')
  t.equal(doc.match('Montaña').text(), 'montaña', here + 'titlecase match')
  t.equal(doc.match('montana').found, false, here + 'ñ is not n')
  t.equal(doc.match('corrio').found, false, here + 'an accent is not its vowel')
  t.equal(doc.match('niño pequeño').text(), 'niño pequeño', here + 'two words')
  t.equal(doc.match('dónde está').text(), '¿Dónde está', here + 'after ¿')
  t.equal(doc.match('dónde está').text('normal'), '¿dónde está', here + 'normal, after ¿')
  t.equal(doc.match('^dónde').found, true, here + '¿ does not block the start')
  t.equal(doc.match('^qué sorpresa$').found, true, here + '¡ ! do not block the anchors')
  t.equal(nlp('EL NIÑO CORRE').match('niño').found, true, here + 'uppercase text')
  t.equal(doc.has('pingüino'), true, here + 'has')
  t.equal(doc.has('caballo'), false, here + 'has not')
  t.equal(doc.if('pingüino').text(), '¿Dónde está el pingüino?', here + 'if')
  t.equal(doc.ifNo('el').text(), '¡Qué sorpresa!', here + 'ifNo')
  t.equal(doc.match('niño .').text(), 'niño pequeño', here + 'wildcard')
  t.equal(doc.match('niño * montaña').text(), 'niño pequeño corrió hacia la montaña', here + 'greedy wildcard')
  t.equal(doc.match('(niño|pingüino)').length, 2, here + 'OR')
  t.equal(doc.match('^el').text(), 'El', here + 'start anchor')
  t.equal(doc.match('montaña$').text(), 'montaña', here + 'end anchor')
  t.equal(doc.match('el [.] pequeño', 0).text(), 'niño', here + 'capture group')
  t.equal(doc.match('el [<quien>.] pequeño').groups('quien').text(), 'niño', here + 'named group')
  t.equal(doc.match('/^ping/').text(), 'pingüino', here + 'regex')
  t.equal(doc.match('/ñ/').length, 3, here + 'regex with ñ')
  t.equal(doc.match('hacia la?').text(), 'hacia la', here + 'optional')
  t.equal(doc.match('!el niño').found, false, here + 'negative')
  t.equal(doc.matchOne('el').text(), 'El', here + 'matchOne')
  t.equal(doc.match('el').length, 2, here + 'two matches')
  t.equal(doc.match('@hasPeriod').length, 1, here + 'hasPeriod')
  t.equal(doc.match('@hasQuestionMark').text(), 'pingüino', here + 'hasQuestionMark')
  t.equal(doc.match('@hasExclamation').text(), 'sorpresa', here + 'hasExclamation')
  t.equal(doc.match('@isTitleCase').length, 3, here + 'titlecase method')
  t.equal(doc.match('el{1,2}').length, 2, here + 'range')
  t.equal(doc.match('~pinguino~', null, { fuzzy: 0.8 }).text(), 'pingüino', here + 'fuzzy')
  t.end()
})

test('look around:', function (t) {
  const doc = nlp(txt)
  t.equal(doc.match('niño').before().text(), 'El', here + 'before')
  t.equal(doc.match('corrió').after().text(), 'hacia la montaña', here + 'after')
  t.equal(doc.match('niño').lookAhead('hacia').text(), 'hacia', here + 'lookAhead')
  t.equal(doc.match('niño').lookAfter('hacia').text(), 'hacia', here + 'lookAfter')
  t.equal(doc.match('corrió').lookBehind('niño').text(), 'niño', here + 'lookBehind')
  t.equal(doc.match('corrió').lookBefore('niño').text(), 'niño', here + 'lookBefore')
  t.equal(doc.match('niño').growRight('pequeño').text(), 'niño pequeño', here + 'growRight')
  t.equal(doc.match('niño').growLeft('el').text(), 'El niño', here + 'growLeft')
  t.equal(doc.match('corrió').grow('(pequeño|hacia)').text(), 'pequeño corrió hacia', here + 'grow')
  t.deepEqual(doc.eq(0).splitOn('corrió').out('array'), ['El niño pequeño', 'corrió', 'hacia la montaña.'], here + 'splitOn')
  t.deepEqual(doc.eq(0).splitBefore('corrió').out('array'), ['El niño pequeño', 'corrió hacia la montaña.'], here + 'splitBefore')
  t.deepEqual(doc.eq(0).splitAfter('corrió').out('array'), ['El niño pequeño corrió', 'hacia la montaña.'], here + 'splitAfter')
  t.deepEqual(doc.eq(0).split('corrió').out('array'), ['El niño pequeño corrió', 'hacia la montaña.'], here + 'split')
  t.deepEqual(doc.eq(1).splitAfter('está').out('array'), ['¿Dónde está', 'el pingüino?'], here + 'split keeps ¿ ?')
  t.end()
})

test('pointers:', function (t) {
  const doc = nlp(txt)
  const a = doc.match('niño pequeño')
  const b = doc.match('pequeño corrió')
  t.equal(a.union(b).text(), 'niño pequeño corrió', here + 'union')
  t.equal(a.and(b).text(), 'niño pequeño corrió', here + 'and')
  t.equal(a.intersection(b).text(), 'pequeño', here + 'intersection')
  t.equal(a.not('pequeño').text(), 'niño', here + 'not')
  t.equal(a.difference('pequeño').text(), 'niño', here + 'difference')
  t.equal(doc.eq(0).complement().text(), '¿Dónde está el pingüino? ¡Qué sorpresa!', here + 'complement')
  t.equal(doc.match('el').unique().length, 1, here + 'unique')
  t.deepEqual(nlp('Uno. Dos. Tres.').reverse().out('array'), ['Tres.', 'Dos.', 'Uno.'], here + 'reverse')
  t.deepEqual(nlp('zorro. casa. barco.').sort('alpha').out('array'), ['barco.', 'casa.', 'zorro.'], here + 'sort alpha')
  t.equal(doc.sort('length').out('array')[0], 'El niño pequeño corrió hacia la montaña.', here + 'sort length')
  t.end()
})

