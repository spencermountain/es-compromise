test('insert and replace:', function (t) {
  const str = 'el niño duerme'
  t.equal(nlp(str).match('niño').insertBefore('pequeño').all().text(), 'el pequeño niño duerme', here + 'insertBefore')
  t.equal(nlp(str).match('niño').prepend('pequeño').all().text(), 'el pequeño niño duerme', here + 'prepend')
  t.equal(nlp(str).match('niño').insertAfter('español').all().text(), 'el niño español duerme', here + 'insertAfter')
  t.equal(nlp(str).match('niño').append('español').all().text(), 'el niño español duerme', here + 'append')
  t.equal(nlp(str).match('niño').insert('español').all().text(), 'el niño español duerme', here + 'insert')
  t.equal(nlp(str).replace('niño', 'ñandú').all().text(), 'el ñandú duerme', here + 'replace')
  t.equal(nlp(str).replace('niño', 'pingüino azul').all().text(), 'el pingüino azul duerme', here + 'replace with two words')
  t.equal(nlp(str).match('niño').replaceWith('león').all().text(), 'el león duerme', here + 'replaceWith')
  t.equal(nlp('el niño duerme. el niño come.').replace('niño', 'león').all().text(), 'el león duerme. el león come.', here + 'replace every match')
  t.equal(nlp('¿Dónde está el niño?').replace('niño', 'león').all().text(), '¿Dónde está el león?', here + 'replace keeps ¿ ?')
  t.equal(nlp('¡Hola niño!').replace('hola', 'Adiós').all().text(), '¡Adiós niño!', here + 'replace keeps ¡ !')
  t.equal(nlp('el niño pequeño duerme').remove('pequeño').text(), 'el niño duerme', here + 'remove')
  t.equal(nlp('el niño pequeño duerme').delete('pequeño').text(), 'el niño duerme', here + 'delete')
  t.equal(nlp('el niño pequeño duerme').match('pequeño').remove().all().text(), 'el niño duerme', here + 'remove self')
  t.equal(nlp('El niño duerme.').concat('La niña también.').length, 2, here + 'concat')
  // the original doc is changed too
  const doc = nlp(str)
  doc.match('niño').replaceWith('león')
  t.equal(doc.text(), 'el león duerme', here + 'replaceWith mutates')
  // new words are parsed, too
  t.deepEqual(nlp('tengo perros').match('perros').insertBefore('tres').all().numbers().get(), [3], here + 'an inserted number')
  t.deepEqual(nlp('tengo tres perros').replace('tres', 'diecisiete').all().numbers().get(), [17], here + 'a replaced number')
  t.end()
})

test('whitespace and punctuation:', function (t) {
  const str = 'el niño duerme'
  t.equal(nlp('  el niño  ').trim().text(), 'el niño', here + 'trim')
  t.equal(nlp(str).hyphenate().text(), 'el-niño-duerme', here + 'hyphenate')
  t.equal(nlp('el-niño-duerme').dehyphenate().text(), str, here + 'dehyphenate')
  t.equal(nlp(str).match('niño').toQuotations().all().text(), 'el "niño" duerme', here + 'toQuotations')
  t.equal(nlp(str).match('niño').toQuotations('«', '»').all().text(), 'el «niño» duerme', here + 'spanish quotes')
  t.equal(nlp(str).match('niño').toParentheses().all().text(), 'el (niño) duerme', here + 'toParentheses')
  t.equal(nlp(str).match('niño').pre('~').all().text(), 'el ~niño duerme', here + 'pre')
  t.equal(nlp(str).match('duerme').post('!').all().text(), 'el niño duerme!', here + 'post')
  t.equal(nlp('«Nos quedamos aquí.»').terms().length, 3, here + 'quotes are not terms')
  t.equal(nlp('«Nos quedamos aquí.»').match('^nos quedamos aquí$').found, true, here + 'guillemets are punctuation')
  t.equal(nlp('«Nos quedamos aquí.»').text(), '«Nos quedamos aquí.»', here + 'quotes survive')
  t.equal(nlp('Nosotros (o sea yo) vamos').match('yo').text(), 'yo', here + 'parentheses are punctuation')
  t.equal(nlp('¿Vienes? ¡Claro que sí!').length, 2, here + '¿? and ¡! end a sentence')
  t.equal(nlp('—¿Vienes? —preguntó ella.').match('vienes').found, true, here + 'a dialogue dash')
  t.end()
})

test('tags:', function (t) {
  const doc = nlp('el ñandú duerme')
  doc.match('ñandú').tag('Ave')
  t.equal(doc.match('#Ave').text(), 'ñandú', here + 'a new tag')
  doc.match('ñandú').unTag('Ave')
  t.equal(doc.has('#Ave'), false, here + 'unTag')
  doc.match('ñandú').tag('#Person')
  t.equal(doc.has('#Person'), true, here + 'tag with a hash')
  t.equal(doc.match('ñandú').has('#Noun'), true, here + 'a Person is a Noun')
  doc.match('ñandú').tag('Verb')
  t.equal(doc.match('ñandú').has('#Noun'), false, here + 'Verb removes Noun')
  const d = nlp('el ñandú duerme')
  d.match('ñandú').tag('Noun').tagSafe('Verb')
  t.equal(d.match('ñandú').has('#Verb'), false, here + 'tagSafe does not over-write')
  t.equal(d.match('ñandú').has('#Noun'), true, here + 'tagSafe keeps the noun')
  t.equal(nlp('tres perros').match('tres').canBe('Verb').found, false, here + 'a value cannot be a verb')
  t.equal(nlp('tres perros').match('tres').canBe('Cardinal').found, true, here + 'a value can be a cardinal')
  // tags by their spanish names
  t.equal(nlp('tres perros').match('#Número').text(), 'tres', here + 'a spanish tag name')
  t.end()
})

test('loops:', function (t) {
  const doc = nlp(txt)
  const arr = []
  doc.forEach(s => arr.push(s.wordCount()))
  t.deepEqual(arr, [7, 4, 2], here + 'forEach')
  t.deepEqual(doc.map(s => ({ words: s.wordCount() }), []), [{ words: 7 }, { words: 4 }, { words: 2 }], here + 'map to an array')
  t.equal(doc.map(s => s.terms().first()).out('array').join(' '), 'El ¿Dónde ¡Qué', here + 'map to a view')
  t.equal(doc.filter(s => s.has('pingüino')).text(), '¿Dónde está el pingüino?', here + 'filter')
  t.equal(doc.find(s => s.has('sorpresa')).text(), '¡Qué sorpresa!', here + 'find')
  t.equal(doc.some(s => s.has('pingüino')), true, here + 'some')
  t.equal(doc.some(s => s.has('caballo')), false, here + 'some - none')
  t.equal(doc.random(1).length, 1, here + 'random')
  t.equal(doc.terms().random(3).length, 3, here + 'random 3')
  t.end()
})

test('clone:', function (t) {
  const doc = nlp('el niño duerme')
  const copy = doc.clone()
  copy.replace('niño', 'león')
  copy.match('duerme').tag('Foo')
  t.equal(doc.text(), 'el niño duerme', here + 'original text is untouched')
  t.equal(copy.text(), 'el león duerme', here + 'clone is changed')
  t.equal(doc.has('#Foo'), false, here + 'original tags are untouched')
  const nums = nlp('tengo 1.234 euros')
  const c = nums.clone()
  c.numbers().add(1)
  t.equal(nums.text(), 'tengo 1.234 euros', here + 'numbers - original')
  t.equal(c.text(), 'tengo 1.235 euros', here + 'numbers - clone')
  t.end()
})

